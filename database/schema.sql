CREATE TABLE IF NOT EXISTS public.tabela_frete (
    id BIGINT PRIMARY KEY,
    company_id BIGINT NOT NULL,
    uf_origem CHAR(2) NOT NULL,
    nome VARCHAR(255),
    ativa BOOLEAN DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS public.objeto_frete (
    id BIGINT PRIMARY KEY,
    tabela_id BIGINT,
    tipo_objeto VARCHAR(20),  -- PARTIDA | COMPONENTE
    uf CHAR(2),               -- destino para COMPONENTEs; NULL = aplica a todos
    base_calculo VARCHAR(50),
    tipo_calculo VARCHAR(50),
    config_faixas JSONB,
    nome VARCHAR(100),
    sobre_frete_partida BOOLEAN DEFAULT FALSE
);

create table IF NOT EXISTS public.users(
	id BIGINT GENERATED BY DEFAULT AS identity primary key,
	name text,
	companyId BIGINT,
    email text,
    password text,
	createdAt timestamp,
	active boolean default TRUE
);

create table IF NOT EXISTS public.companies(
	id BIGINT GENERATED BY DEFAULT AS identity primary key,
	name text,
	social_name text,
	document text,
	createdAt timestamp,
	active boolean default TRUE,
	apikey VARCHAR(22) NOT NULL
);

create table IF NOT EXISTS public.external_apikeys(
	id BIGINT primary key,
	custom_name text,
	apikey VARCHAR(22) NOT NULL,
	companyId BIGINT,
	active boolean
);

-- Índice GIN para buscas em campos JSONB
CREATE INDEX IF NOT EXISTS idx_objeto_frete_faixas ON objeto_frete USING GIN (config_faixas);

CREATE UNIQUE INDEX IF NOT EXISTS uq_companies_apikey
    ON companies (apikey);

CREATE UNIQUE INDEX IF NOT EXISTS uq_external_apikeys_apikey
    ON external_apikeys (apikey);

DROP INDEX IF EXISTS uq_tabela_frete_uf_origem_ativa;
DROP INDEX IF EXISTS uq_tabela_frete_company_uf_origem_ativa;
